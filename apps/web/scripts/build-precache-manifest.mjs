#!/usr/bin/env node
/*
 * Generates `out/sw-manifest.js` listing every URL the service
 * worker should precache. Run as a `postbuild` step so the
 * manifest reflects the actual artefacts Next.js just emitted —
 * hand-listing chunks would break on every code change because
 * Next content-hashes their filenames.
 *
 * What's included:
 *   - The HTML shell (`index.html`) and top-level static assets
 *     (favicon, icons, manifest, the runtime-rendered `config.js`
 *     placeholder if present).
 *   - Everything under `_next/static/`: hashed JS chunks, CSS,
 *     `.wasm` blobs in `media/`. Content-hashed, immutable, cheap
 *     to cache.
 *
 * What's excluded:
 *   - `sw.js` itself and `sw-manifest.js` (a worker caching itself
 *     is a footgun for updates).
 *   - `_next/static/<BUILD_ID>/_buildManifest.js` etc. are *kept*
 *     because Next loads them at boot and not caching them would
 *     break offline navigation.
 *   - `404.html`, `index.txt` — neither is fetched at runtime by
 *     the static export, so they'd just waste cache quota.
 *   - Anything outside `out/`.
 *
 * Versioning:
 *   - `version` is a short SHA-256 of (concatenated URL list +
 *     each file's bytes). Hashing the actual contents — not just
 *     the size — catches deploys that swap a non-hashed asset
 *     (notably `index.html` or `config.js`) for one of identical
 *     byte length; otherwise the cache key wouldn't change and
 *     stale bytes would survive forever. The service worker keys
 *     its CacheStorage by this version, so old caches get evicted
 *     on activate.
 *
 * Importable via `import { buildManifest } from '...'` so the
 * vitest test can drive it without spawning a subprocess.
 */

import { createHash } from "node:crypto";
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, join, posix, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const DEFAULT_OUT_DIR = join(HERE, "..", "out");
const MANIFEST_FILENAME = "sw-manifest.js";

const EXCLUDE_BASENAMES = new Set([
	"sw.js",
	MANIFEST_FILENAME,
	"404.html",
	"index.txt",
]);

const EXCLUDE_DIR_BASENAMES = new Set(["404"]);

/**
 * Recursively collects every file under `dir`, returning paths
 * relative to `root` with forward-slash separators (URL form).
 */
async function walk(dir, root) {
	const out = [];
	const entries = await readdir(dir, { withFileTypes: true });
	for (const entry of entries) {
		const full = join(dir, entry.name);
		if (entry.isDirectory()) {
			if (EXCLUDE_DIR_BASENAMES.has(entry.name)) continue;
			out.push(...(await walk(full, root)));
			continue;
		}
		if (!entry.isFile()) continue;
		if (EXCLUDE_BASENAMES.has(entry.name)) continue;
		// Excludes anything containing an `api/` path segment — keeps
		// the SW honest even if a future build ever lands API
		// artefacts in `out/`. `rel` is root-relative with no leading
		// slash (e.g. `api/foo.json` or `_next/static/api/leak.json`),
		// so a plain `.includes("/api/")` would miss the root-level
		// case and pass `api/foo.json` straight into `cache.addAll`,
		// where a 4xx would fail the entire install.
		const rel = relative(root, full).split(sep).join(posix.sep);
		if (rel.startsWith("api/") || rel.includes("/api/")) continue;
		out.push(rel);
	}
	return out;
}

/**
 * Builds the manifest object for a given `out/` directory.
 * Pure-ish (touches disk, but no globals); exported for tests.
 */
export async function buildManifest(outDir) {
	const files = await walk(outDir, outDir);
	files.sort();
	const urls = files.map((f) => `./${f}`);
	const hash = createHash("sha256");
	for (const f of files) {
		const content = await readFile(join(outDir, f));
		hash.update(f);
		hash.update("\0");
		hash.update(content);
		hash.update("\0");
	}
	const version = hash.digest("hex").slice(0, 16);
	return { version, urls };
}

/**
 * Serialises a manifest into the JS the SW expects to find via
 * `importScripts('./sw-manifest.js')`.
 */
export function renderManifest(manifest) {
	const json = JSON.stringify(manifest, null, "\t");
	return `// Generated by scripts/build-precache-manifest.mjs — do not edit by hand.\nself.__OPFS_PRECACHE = ${json};\n`;
}

async function main() {
	const outDir = process.argv[2] ? process.argv[2] : DEFAULT_OUT_DIR;
	try {
		await stat(outDir);
	} catch {
		// `next build` without `NEXT_OUTPUT_EXPORT=1` skips static
		// export, so `out/` won't exist. The SW is only meaningful
		// for the export build (GitHub Pages), so silently skip
		// rather than fail the wider `pnpm build`.
		console.warn(
			`[sw-manifest] no ${outDir} directory; skipping precache manifest`,
		);
		return;
	}
	const manifest = await buildManifest(outDir);
	const dest = join(outDir, MANIFEST_FILENAME);
	await writeFile(dest, renderManifest(manifest), "utf8");
	console.info(
		`[sw-manifest] wrote ${manifest.urls.length} urls @ ${manifest.version} → ${relative(process.cwd(), dest)}`,
	);
}

const invokedDirectly =
	import.meta.url === `file://${process.argv[1]}` ||
	process.argv[1]?.endsWith("build-precache-manifest.mjs");
if (invokedDirectly) {
	await main();
}
